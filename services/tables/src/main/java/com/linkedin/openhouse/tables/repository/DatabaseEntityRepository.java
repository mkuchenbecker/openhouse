package com.linkedin.openhouse.tables.repository;

import com.linkedin.openhouse.tables.model.DatabaseDto;
import com.linkedin.openhouse.tables.model.DatabaseDtoPrimaryKey;
import com.linkedin.openhouse.tables.model.DatabasePropertiesUpdateDto;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import org.springframework.data.repository.CrudRepository;
import org.springframework.stereotype.Repository;

/**
 * Repository for the persisted database entity (UUID, name, properties), which lives in the
 * HouseTables Service and is independent of table metadata. The production implementation is {@link
 * com.linkedin.openhouse.tables.repository.impl.DatabaseEntityRepositoryImpl} over the generated
 * HouseTables {@code DatabaseApi}; test contexts without a HouseTables Service substitute an
 * H2-backed JPA interface marked {@code @Primary}, exactly as {@link
 * com.linkedin.openhouse.internal.catalog.repository.HouseTableRepository} and {@link
 * com.linkedin.openhouse.tables.toggle.repository.ToggleStatusesRepository} are substituted.
 *
 * <p>Nothing in this repository reads or writes table rows: creating a table does not create a
 * database entity, and deleting a database entity does not touch tables.
 */
@Repository
public interface DatabaseEntityRepository
    extends CrudRepository<DatabaseDto, DatabaseDtoPrimaryKey> {

  /** Look up the database entity by name, ignoring case. Empty when absent. */
  Optional<DatabaseDto> findByDatabaseIdIgnoreCase(String databaseId);

  /** Whether a database entity with this name exists, ignoring case. */
  boolean existsByDatabaseIdIgnoreCase(String databaseId);

  /**
   * Create the database entity. The UUID is generated by the store, never taken from the caller.
   *
   * @throws com.linkedin.openhouse.common.exception.AlreadyExistsException if a database with this
   *     name exists, ignoring case.
   */
  DatabaseDto create(DatabaseDto databaseDto);

  /**
   * Apply a sparse property update following the Iceberg REST catalog {@code updateProperties}
   * contract: set every key in {@code updates}, remove every key in {@code removals}, leave every
   * other property untouched.
   *
   * @throws com.linkedin.openhouse.common.exception.NoSuchEntityException if absent.
   * @throws com.linkedin.openhouse.common.exception.EntityConcurrentModificationException if the
   *     entity changed concurrently.
   */
  DatabasePropertiesUpdateDto updateProperties(
      String databaseId, Map<String, String> updates, List<String> removals);
}
