package com.linkedin.openhouse.tables.api.spec.v0.request;

import static com.linkedin.openhouse.common.api.validator.ValidatorConstants.ALPHA_NUM_UNDERSCORE_ERROR_MSG;
import static com.linkedin.openhouse.common.api.validator.ValidatorConstants.ALPHA_NUM_UNDERSCORE_REGEX;

import com.google.gson.Gson;
import io.swagger.v3.oas.annotations.media.Schema;
import java.util.Map;
import javax.annotation.Nullable;
import javax.validation.constraints.NotEmpty;
import javax.validation.constraints.Pattern;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NoArgsConstructor;

/**
 * Request to create a database entity, following the Iceberg REST catalog {@code createNamespace}
 * shape: a name and optional properties. The UUID is generated by the server and cannot be
 * supplied.
 */
@Builder
@EqualsAndHashCode
@Getter
@AllArgsConstructor(access = AccessLevel.PROTECTED)
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class CreateDatabaseRequestBody {
  @Schema(description = "Unique Resource identifier for the Database", example = "my_database")
  @NotEmpty(message = "databaseId cannot be empty")
  @Pattern(regexp = ALPHA_NUM_UNDERSCORE_REGEX, message = ALPHA_NUM_UNDERSCORE_ERROR_MSG)
  String databaseId;

  @Schema(
      description = "Optional key-value properties of the database",
      example = "{\"retention.days\": \"30\"}")
  @Nullable
  Map<String, String> properties;

  public String toJson() {
    return new Gson().toJson(this);
  }
}
